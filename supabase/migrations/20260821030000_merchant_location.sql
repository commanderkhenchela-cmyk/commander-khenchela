alter table merchants add column longitude double precision;

comment on column merchants.latitude is 'خط عرض موقع المحل — يملؤه التاجر من لوحة تحكمه. لا قيمة = المحل لن يظهر في قسم "الأقرب إليك"، دون أي افتراض خاطئ.';
