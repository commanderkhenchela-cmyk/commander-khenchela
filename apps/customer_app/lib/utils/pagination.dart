/// منطق صفحة واحدة من Pagination خادمي — مستخرَج كدالة صِرفة قابلة
/// للاختبار مباشرة (بدون شبكة/Widget)، بدل تكراره يدويًا داخل كل شاشة
/// (Merchants/Orders/Search كانت الثلاثة تكتب نفس السطر:
/// `hasMore = items.length == pageSize`).
///
/// القاعدة: صفحة أرجعت *أقل* من `pageSize` صف هي بالضرورة آخر صفحة —
/// لا حاجة لطلب صفحة إضافية للتأكد. صفحة أرجعت *بالضبط* `pageSize` صف
/// **قد** تكون آخر صفحة أيضًا (لو كان عدد الصفوف الكلي مضاعفًا تمامًا
/// لحجم الصفحة) — في هذه الحالة نفترض تفاؤليًا وجود المزيد ونترك
/// الطلب التالي (الذي سيُرجِع صفرًا) يصحّح الافتراض، بدل استعلام عدّ
/// إضافي لكل صفحة لمجرّد معرفة ذلك مسبقًا.
bool hasMorePages({required int fetchedCount, required int pageSize}) {
  assert(pageSize > 0, 'pageSize يجب أن يكون أكبر من صفر');
  return fetchedCount == pageSize;
}
