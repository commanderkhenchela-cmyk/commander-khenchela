-- ============================================================
-- Migration: نبضة يومية داخلية (pg_cron) لمنع إيقاف المشروع تلقائيًا
--
-- خطة Supabase المجانية توقف المشروع (pause) بعد 7 أيام متتالية بلا
-- نشاط API حقيقي يصل لقاعدة البيانات. أول محاولة لحل هذا كانت "نبضة"
-- خارجية (Routine مجدولة تستدعي REST API من بيئة Claude Code) — فشلت
-- لأن بيئة الجلسة نفسها محظور عليها الوصول لنطاق Supabase (سياسة شبكة
-- تنظيمية، 403 عند CONNECT)، لا علاقة لها بحالة المشروع الفعلية.
--
-- الحل الصحيح: نبضة داخلية عبر pg_cron — تعمل من داخل قاعدة البيانات
-- نفسها، لا تعتمد على أي شبكة خارجية أو بيئة تشغيل خارجية إطلاقًا،
-- وهي الطريقة الموصى بها رسميًا من Supabase لهذه المشكلة بالذات.
--
-- الاستعلام نفسه بسيط وبلا أي أثر جانبي (SELECT للقراءة فقط، جدول
-- app_branding — صف واحد ثابت أصلًا) — الهدف الوحيد هو تسجيل نشاط
-- حقيقي على قاعدة البيانات، لا جلب بيانات فعلية يُستخدَم فـ أي مكان.
-- ============================================================

create extension if not exists pg_cron with schema extensions;

select cron.schedule(
  'keep-project-alive-daily',
  '0 9 * * *', -- كل يوم الساعة 9 صباحًا UTC (10 صباحًا بتوقيت الجزائر)
  $$ select id from app_branding limit 1; $$
);

comment on extension pg_cron is 'مُفعَّلة فقط لمهمة النبضة اليومية (keep-project-alive-daily) — تمنع إيقاف المشروع التلقائي فـ الخطة المجانية بعد 7 أيام بلا نشاط. راجع تعليق هذا الـ migration للتفصيل الكامل.';
