  id smallint primary key,
  name text not null
);

comment on table wilayas is 'قائمة الولايات الجزائرية الـ 58 (بيانات مرجعية ثابتة)';

-- جدول البلديات: مرتبطة بولايتها عبر wilaya_id.
-- id = الكود الرسمي للبلدية (مثال: 4001 = خنشلة).
create table communes (
  id integer primary key,
  wilaya_id smallint not null references wilayas (id),
  name text not null
);

comment on table communes is 'قائمة البلديات، مرتبطة بالولاية. تُضاف بلديات الولايات الأخرى تدريجيًا دون تعديل بنية الجدول.';

create index communes_wilaya_id_idx on communes (wilaya_id);

